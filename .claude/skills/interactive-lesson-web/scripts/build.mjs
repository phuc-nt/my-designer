// Builds one lesson page from its lesson.js and the rendered video project it points at (META.video):
// the page kit, the video's own 3D world and models, its mixed sound track, its frames and word timings.
//   node build.mjs <lesson-dir> <out-dir> [--back "<href>|<text>"] [--next "<href>|<title>"]
// A lesson dir may hold lib/ with files that replace the video's assets/lib/ ones (same relative paths),
// for a world that needs a page-only option the video does not.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { pathToFileURL } from "node:url";

const KIT = path.join(path.dirname(new URL(import.meta.url).pathname), "../kit");
const args = process.argv.slice(2);
const option = (name) => {
  const at = args.indexOf(name);
  return at >= 0 ? args.splice(at, 2)[1] : null;
};
const back = option("--back");
const next = option("--next");
const [lessonArg, outArg] = args;
if (!lessonArg || !outArg) throw new Error("usage: node build.mjs <lesson-dir> <out-dir> [--back '<href>|<text>'] [--next '<href>|<title>']");
const LESSON = path.resolve(lessonArg);
const OUT = path.resolve(outArg);

const { META, PARTS } = await import(pathToFileURL(path.join(LESSON, "lesson.js")).href);
const VIDEO = path.resolve(LESSON, META.video);
const video = (...p) => path.join(VIDEO, ...p);
for (const need of ["index.html", "SCRIPT.md", "renders/video.mp4", "assets/lib/world/world.js"]) {
  if (!fs.existsSync(video(need))) throw new Error(`${need} missing in ${VIDEO}`);
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, "assets/fonts"), { recursive: true });
for (const f of ["app.js", "style.css"]) fs.copyFileSync(path.join(KIT, f), path.join(OUT, f));
fs.copyFileSync(path.join(LESSON, "lesson.js"), path.join(OUT, "lesson.js"));
fs.cpSync(video("assets/lib"), path.join(OUT, "assets/lib"), { recursive: true });
if (fs.existsSync(video("assets/models"))) fs.cpSync(video("assets/models"), path.join(OUT, "assets/models"), { recursive: true });
if (fs.existsSync(path.join(LESSON, "lib"))) fs.cpSync(path.join(LESSON, "lib"), path.join(OUT, "assets/lib"), { recursive: true });
fs.copyFileSync(video("assets/fonts/PlusJakartaSans-VN.woff2"), path.join(OUT, "assets/fonts/PlusJakartaSans-VN.woff2"));

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const [backHref, backText] = (back ?? "").split("|");
const [nextHref, nextTitle] = (next ?? "").split("|");
const page = fs
  .readFileSync(path.join(KIT, "index.html"), "utf8")
  .replace("{{TITLE}}", esc(META.title))
  .replace("{{DESCRIPTION}}", esc(META.description ?? META.heading))
  .replace("{{BACK}}", back ? `<a class="back" href="${esc(backHref)}">← ${esc(backText || "Tất cả bài")}</a>` : "")
  .replace("{{KICKER}}", esc(META.kicker ?? "Bài giảng tương tác"))
  .replace("{{HEADING}}", esc(META.heading))
  .replace("{{NEXT}}", next ? `<a class="next-lesson" href="${esc(nextHref)}"><small>Bài tiếp theo</small><b>${esc(nextTitle)}</b></a>` : "");
fs.writeFileSync(path.join(OUT, "index.html"), page);

// chapters: one per frame of the video, titled from SCRIPT.md
const html = fs.readFileSync(video("index.html"), "utf8");
const starts = [...html.matchAll(/data-composition-src="compositions\/frames\/[^"]+\.html"\s+data-start="([\d.]+)"/g)].map((m) => +m[1]);
const titles = [...fs.readFileSync(video("SCRIPT.md"), "utf8").matchAll(/^## Line \d+ — (.+) \(Frame (\d+)\)\s*$/gm)].map((m) => m[1]);
if (starts.length !== titles.length) throw new Error(`frames in index.html ${starts.length} vs SCRIPT.md ${titles.length}`);
const chapters = starts.map((start, i) => ({ n: i + 1, start, title: titles[i] }));

// word timings; a video without caption_groups.json gets none, and the page hides its caption line
const duration = () => +execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", video("renders/video.mp4")]).toString();
let total;
let captions = [];
if (fs.existsSync(video("caption_groups.json"))) {
  const cap = JSON.parse(fs.readFileSync(video("caption_groups.json"), "utf8"));
  total = cap.total_duration_s;
  captions = cap.groups.map((g) => ({ f: g.frame, s: g.start, e: g.end, w: g.words.map((w) => [w.text, w.start, w.end]) }));
} else {
  total = Math.round(duration() * 100) / 100;
  if (META.captions !== false) console.warn("no caption_groups.json: set META.captions = false");
  if (PARTS.some((p) => p.ask)) throw new Error("questions need caption_groups.json to know when they are asked");
}

fs.writeFileSync(
  path.join(OUT, "data.js"),
  `// generated by build.mjs from ${path.basename(VIDEO)}\nexport const TOTAL = ${total};\nexport const CHAPTERS = ${JSON.stringify(chapters)};\nexport const CAPTIONS = ${JSON.stringify(captions)};\n`,
);

// the sound of the rendered video, untouched: voice, music and effects as mixed
execFileSync("ffmpeg", ["-v", "error", "-y", "-i", video("renders/video.mp4"), "-vn", "-c:a", "copy", "-movflags", "+faststart", path.join(OUT, "lesson.m4a")]);

// the same checks the page makes when it loads, so a wrong frame number fails here
for (const p of [...PARTS]) {
  for (const n of [...p.frames, p.explain ?? p.frames[0], p.ask?.frame ?? p.frames[0]]) {
    if (!chapters[n - 1]) throw new Error(`${p.label}: frame ${n} does not exist (video has ${chapters.length})`);
  }
}
const sizeMb = (fs.statSync(path.join(OUT, "lesson.m4a")).size / 1e6).toFixed(1);
console.log(`${path.basename(LESSON)}: ${chapters.length} frames, ${captions.length} caption groups, ${PARTS.filter((p) => p.ask).length} questions, ${total}s, sound ${sizeMb} MB`);

// Narration word timings -> assets/lib/world/cues.js, in absolute seconds of the video.
// Run from the project root after every change to the voice: node scripts/build-cues.mjs
import { readFileSync, writeFileSync } from "node:fs";

const meta = JSON.parse(readFileSync("audio_engine_meta.json", "utf8"));
const r = (x) => Math.round(x * 1000) / 1000;
let t = 0;
const frames = meta.voices.map((v, i) => {
  const f = {
    n: i + 1,
    start: r(t),
    dur: v.duration_s,
    words: v.words.map((w) => ({ w: w.text, s: r(t + w.start), e: r(t + w.end) })),
  };
  t += v.duration_s;
  return f;
});
const out = `// generated by scripts/build-cues.mjs from audio_engine_meta.json; do not edit\nexport const CUES = ${JSON.stringify({ total: r(t), frames })};\n`;
writeFileSync("assets/lib/world/cues.js", out);
console.log(`cues: ${frames.length} frames, ${r(t)} s`);
